// Build-only compatibility facade generator for the checksum-verified Distribution
// source tree. It exposes the maintained 3.1 client implementation at the legacy
// public import paths; it does not copy the old registry server implementation.
package main

import (
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	if len(os.Args) != 2 {
		panic("usage: distribution_compat <distribution-3.1-source-directory>")
	}
	root := os.Args[1]
	for _, pair := range [][2]string{
		{"internal/client", "registry/client"},
		{"internal/client/auth", "registry/client/auth"},
		{"internal/client/auth/challenge", "registry/client/auth/challenge"},
		{"internal/client/transport", "registry/client/transport"},
		{"internal/dcontext", "context"},
	} {
		if err := facade(root, pair[0], pair[1]); err != nil {
			panic(err)
		}
	}
}

func facade(root, source, destination string) error {
	packages, err := parser.ParseDir(token.NewFileSet(), filepath.Join(root, source),
		func(info os.FileInfo) bool { return !strings.HasSuffix(info.Name(), "_test.go") }, 0)
	if err != nil {
		return err
	}
	if len(packages) != 1 {
		return fmt.Errorf("expected one package in %s", source)
	}
	declarations := map[string]string{}
	for _, pkg := range packages {
		for _, file := range pkg.Files {
			for _, declaration := range file.Decls {
				switch node := declaration.(type) {
				case *ast.FuncDecl:
					if node.Recv == nil && node.Name.IsExported() {
						declarations[node.Name.Name] = "var"
					}
				case *ast.GenDecl:
					for _, spec := range node.Specs {
						switch value := spec.(type) {
						case *ast.TypeSpec:
							if value.Name.IsExported() {
								if value.TypeParams != nil {
									return fmt.Errorf("generic type requires explicit review: %s", value.Name)
								}
								declarations[value.Name.Name] = "type"
							}
						case *ast.ValueSpec:
							for _, name := range value.Names {
								if name.IsExported() {
									declarations[name.Name] = node.Tok.String()
								}
							}
						}
					}
				}
			}
		}
	}
	names := make([]string, 0, len(declarations))
	for name := range declarations {
		names = append(names, name)
	}
	sort.Strings(names)
	var output strings.Builder
	fmt.Fprintf(&output, "// Code generated by Launchpad distribution_compat.go; DO NOT EDIT.\n")
	fmt.Fprintf(&output, "// Legacy path facade over the maintained, pinned Distribution client.\n")
	fmt.Fprintf(&output, "package %s\n\nimport upstream %q\n\n", filepath.Base(destination),
		"github.com/distribution/distribution/v3/"+source)
	for _, name := range names {
		fmt.Fprintf(&output, "%s %s = upstream.%s\n", declarations[name], name, name)
	}
	formatted, err := format.Source([]byte(output.String()))
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Join(root, destination), 0755); err != nil {
		return err
	}
	path := filepath.Join(root, destination, "launchpad_compat.go")
	file, err := os.OpenFile(path, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0644)
	if err != nil {
		return err
	}
	if _, err := file.Write(formatted); err != nil {
		file.Close()
		return err
	}
	return file.Close()
}
